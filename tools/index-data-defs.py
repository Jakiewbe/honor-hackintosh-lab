#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Classify data symbols of the OGKM tree: defined / macro-defined / build-generated / absent.

Why this exists
---------------
`tools/index-definitions.py` only understands *function* shapes. A class descriptor or global table is
`TYPE name = ...`, a GUID is `GUID_CONST(name, ...)`, an ID string is generated by the Makefile, and a
global may be a bare `TYPE name;` tentative definition. Every one of these was missed at least once in
this project, and a zero-hit was mistaken for "source missing". This tool reports *which* shape matched
and never reports "absent" for something a build step produces.

Shapes
------
DEF        `TYPE name = ...`, `TYPE name[...]`, or a top-level tentative `TYPE name;` (no leading space)
MACRO      name as the first argument of an UPPER_CASE macro at line start, e.g. `GUID_CONST(name, ...)`
GENERATED  name appears inside a `GENERATE_*` macro block in a Makefile / .mk
NONE       none of the above (only then is "not in the tree" a fair statement)

Usage:
    python tools/index-data-defs.py <tree> <names-file> [--json out.json]
"""
import json
import re
import sys
from pathlib import Path

EXTS = {".c", ".h", ".cpp", ".hpp", ".inc"}
BUILD = {"Makefile", "makefile", "Kbuild"}
BUILD_SUFFIX = {".mk"}
LINE_COMMENT = re.compile(r"//.*$")

VAR_DEF = re.compile(r"^\s*(?!extern\b)[^=;{}]*?\b([A-Za-z_]\w{2,})\s*(?:=|\[)")
TENTATIVE = re.compile(r"^(?!extern\b)[A-Za-z_][\w \t\*]*\b([A-Za-z_]\w{2,})\s*;\s*$")
# A bare `extern TYPE name;` is a declaration. Recorded separately so it can never be reported as a
# definition, which is exactly the mistake this tool exists to prevent.
EXTERN_DECL = re.compile(r"^\s*extern\b[^;]*?\b([A-Za-z_]\w{2,})\s*(?:;|\[)")
MACRO_CALL = re.compile(r"^\s*[A-Z_][A-Z_0-9]*\s*\(\s*([A-Za-z_]\w{2,})\s*,")
GENERATE = re.compile(r"GENERATE_[A-Z_]+")


def main():
    tree = Path(sys.argv[1])
    names = {l.strip().lstrip("_") for l in Path(sys.argv[2]).read_text(encoding="utf-8-sig").splitlines() if l.strip()}
    out = Path(sys.argv[sys.argv.index("--json") + 1]) if "--json" in sys.argv else None

    found = {"DEF": {}, "MACRO": {}, "GENERATED": {}, "DECL": {}}
    files = 0
    for p in sorted(tree.rglob("*")):
        if not p.is_file() or ".git" in p.parts:
            continue
        is_build = p.name in BUILD or p.suffix in BUILD_SUFFIX
        if p.suffix not in EXTS and not is_build:
            continue
        files += 1
        try:
            lines = p.read_text(encoding="utf-8", errors="replace").splitlines()
        except OSError:
            continue
        rel = p.relative_to(tree).as_posix()
        for i, raw in enumerate(lines):
            line = LINE_COMMENT.sub("", raw)
            if is_build:
                if GENERATE.search(line):
                    for w in lines[i:i + 4]:
                        for tok in re.findall(r"\b([A-Za-z_]\w{2,})\b", w):
                            if tok.lstrip("_") in names:
                                found["GENERATED"].setdefault(tok.lstrip("_"), []).append(f"{rel}:{i + 1}")
                continue
            md = EXTERN_DECL.match(line)
            if md and md.group(1).lstrip("_") in names:
                found["DECL"].setdefault(md.group(1).lstrip("_"), []).append(f"{rel}:{i + 1}")
                continue
            for key, rx in (("MACRO", MACRO_CALL), ("DEF", VAR_DEF), ("DEF", TENTATIVE)):
                m = rx.match(line)
                if m and m.group(1).lstrip("_") in names:
                    found[key].setdefault(m.group(1).lstrip("_"), []).append(f"{rel}:{i + 1}")
                    break

    seen = set(found["DEF"]) | set(found["MACRO"]) | set(found["GENERATED"]) | set(found["DECL"])
    missing = sorted(names - seen)
    print(f"scanned {files} files; {len(found['DEF'])} defined, {len(found['MACRO'])} macro-defined, "
          f"{len(found['GENERATED'])} build-generated, {len(missing)} absent")
    for key in ("DEF", "MACRO", "GENERATED", "DECL"):
        for n in sorted(found[key]):
            print(f"  {key:9} {n:34} {found[key][n][0]}")
    for n in missing:
        print(f"  NONE      {n}")
    if out:
        out.write_text(json.dumps({"definitions": found["DEF"], "macros": found["MACRO"],
                                   "generated": found["GENERATED"], "declarations": found["DECL"],
                                   "missing": missing}, indent=1),
                       encoding="utf-8")
        print("written:", out)
    return 0 if not missing else 1


if __name__ == "__main__":
    sys.exit(main())
